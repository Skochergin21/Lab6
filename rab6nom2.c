/*
 * Вариант 14
 *
 *          | -x^3 + 9,      при x <= 13
 *   F(x) = |
 *          | 3 / (x + 1),   при x > 13
 *
 * Контрольные примеры (посчитал руками):
 * первое условие x <= 13:
 *   x = -2  -> -(-8) + 9 = 8 + 9  = 17
 *   x = 0   -> 0 + 9              = 9
 *   x = 2   -> -8 + 9             = 1
 *   x = 13  -> -2197 + 9          = -2188   (граница, тут еще первая формула)
 *
 * второе условие x > 13:
 *   x = 13,5 -> 3 / 14,5           = 0,206897  (сразу после границы)
 *   x = 14   -> 3 / 15             = 0,2
 *   x = 29   -> 3 / 30             = 0,1
 *
 * На ноль делить будет только при x = -1, а вторая формула
 * работает только когда x > 13, так что деления на ноль не будет.
 */
#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <locale.h>

int main()
{
    double x;

    setlocale(LC_ALL, "Rus");

    printf("Введите x: ");
    if (scanf("%lf", &x) != 1)
    {
        printf("Ошибка! Надо ввести число\n");
        return 1;
    }

    /* с использованием тернарной операции в printf */
    printf("F(%g) = %f, формула: %s\n",
        x,
        (x <= 13) ? (-x * x * x + 9) : (3 / (x + 1)),
        (x <= 13) ? "-x^3 + 9 (x <= 13)" : "3/(x+1) (x > 13)");

    return 0;
}
